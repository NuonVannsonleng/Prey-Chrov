// Exports every generated texture as a PNG template plus its frame list, for artists replacing
// the code-drawn art with hand-drawn art (see docs/ART_PIPELINE.md).
// Usage: npm run build && npm run art:templates   →   ./art-templates/
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { preview } from 'vite';
import { chromium } from 'playwright-core';

const OUT = 'art-templates';
const PORT = Number(process.env.ART_PORT ?? 4327);
if (!existsSync('dist/index.html')) {
  console.error('No build found: run npm run build first.');
  process.exit(2);
}
mkdirSync(OUT, { recursive: true });
const server = await preview({ preview: { port: PORT, strictPort: true }, logLevel: 'silent' });
let browser;
for (const channel of ['msedge', 'chrome']) {
  try {
    browser = await chromium.launch({ channel, headless: true });
    break;
  } catch {
    /* try the next browser */
  }
}
if (!browser) {
  console.error('Needs Microsoft Edge or Google Chrome installed.');
  await server.close();
  process.exit(2);
}
try {
  const page = await browser.newPage();
  // Templates are the generated art, even if public/art already overrides some of it.
  await page.route('**/art/manifest.json', (r) => r.fulfill({ contentType: 'application/json', body: '{"textures":{}}' }));
  await page.goto(`http://localhost:${PORT}/?debug`);
  await page.waitForFunction(() => window.__preyChrov?.scene.isActive('Menu'), null, { timeout: 30000 });
  const textures = await page.evaluate(() => {
    const game = window.__preyChrov;
    const out = [];
    for (const key of game.textures.getTextureKeys()) {
      if (!key.startsWith('tex-')) continue;
      const tex = game.textures.get(key);
      const src = tex.getSourceImage();
      if (!(src instanceof HTMLCanvasElement)) continue;
      const frames = tex
        .getFrameNames()
        .map((name) => {
          const f = tex.get(name);
          return { name, x: f.cutX, y: f.cutY, w: f.cutWidth, h: f.cutHeight };
        })
        .sort((a, b) => a.y - b.y || a.x - b.x);
      out.push({ key, width: src.width, height: src.height, png: src.toDataURL('image/png'), frames });
    }
    return out;
  });
  const index = [];
  for (const t of textures) {
    writeFileSync(`${OUT}/${t.key}.png`, Buffer.from(t.png.split(',')[1], 'base64'));
    writeFileSync(`${OUT}/${t.key}.frames.json`, JSON.stringify({ texture: t.key, width: t.width, height: t.height, frames: t.frames }, null, 2) + '\n');
    // Sheets with no named frames are used whole (e.g. the ground tileset: 32×32 tiles by index, see TILE in src/textures.ts).
    index.push(`| \`${t.key}\` | ${t.width}×${t.height} | ${t.frames.length || (t.key === 'tex-tiles' ? 'tileset: 32×32 tiles by TILE index' : 'whole image')} |`);
  }
  writeFileSync(
    `${OUT}/README.md`,
    [
      '# Art templates',
      '',
      'Generated by `npm run art:templates` from the current build. Paint over a PNG, keeping its exact size and the frame positions listed in its `.frames.json`, then follow docs/ART_PIPELINE.md.',
      '',
      '| Texture | Size | Frames |',
      '| --- | --- | --- |',
      ...index,
      '',
    ].join('\n'),
  );
  console.log(`Exported ${textures.length} textures to ./${OUT}/`);
} finally {
  await browser.close();
  await server.close();
}
